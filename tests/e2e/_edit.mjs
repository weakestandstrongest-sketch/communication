import { createRequire } from "node:module";
import { createUser, signedInContext, APP_URL } from "./session.mjs";
const { chromium, devices } = createRequire(import.meta.url)("playwright");
const jst = new Date(Date.now() + 9 * 3600_000);
const at = (h) => new Date(Date.UTC(jst.getUTCFullYear(), jst.getUTCMonth(), jst.getUTCDate(), h - 9)).toISOString();
const browser = await chromium.launch();
const u = await createUser("編集 確認");
const g = (await u.client.rpc("create_group", { p_name: "テスト", p_color: "violet" })).data;
const ge = (await u.client.rpc("create_event", { p_group_id: g, p_title: "グループ予定", p_starts_at: at(10), p_ends_at: at(11), p_post_to_chat: false })).data;
const ad = (await u.client.rpc("create_personal_event", { p_title: "終日個人", p_starts_at: at(0), p_ends_at: at(23), p_all_day: true })).data;
const ne = (await u.client.rpc("create_personal_event", { p_title: "終了なし", p_starts_at: at(12) })).data;
const pe = (await u.client.rpc("create_personal_event", { p_title: "個人予定", p_starts_at: at(15), p_ends_at: at(16) })).data;
const ctx = await signedInContext(browser, u, { ...devices["iPhone 13"] });
const p = await ctx.newPage();
p.on("console", (m) => m.type() === "error" && console.log("console:", m.text()));
p.on("pageerror", (e) => console.log("pageerror:", e.message));
await p.goto(`${APP_URL}/calendar`);
await p.waitForTimeout(1000);
await p.getByRole("tab", { name: "タイムライン" }).click();
await p.getByRole("link", { name: /グループ予定/ }).click();
await p.waitForURL(/\/events\//);
await p.getByRole("button", { name: /メニュー|その他|…/ }).first().click().catch((e) => console.log("menu click failed", e.message.split("\n")[0]));
await p.waitForTimeout(500);
console.log("menu items:", await p.getByRole("menuitem").allInnerTexts());
await p.getByRole("dialog").getByText("編集", { exact: true }).click().catch((e) => console.log("edit click failed", e.message.split("\n")[0]));
await p.waitForTimeout(1500);
console.log("url", p.url());
await p.screenshot({ path: process.argv[2] + "/edit-ui.png" });
await browser.close();
